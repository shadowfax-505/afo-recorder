#!/usr/bin/env python3
"""Export gaitmap's pre-trained Roth stride HMM to a small JS module.

Source: gaitmap_mad 2.6.0, stride_segmentation/hmm/_pre_trained_models/
fallriskpd_at_lab_model.json (AGPL-3.0-or-later, (c) the gaitmap authors,
Machine Learning and Data Analytics Lab, FAU Erlangen-Nuernberg).
Model from Roth et al., J NeuroEng Rehabil 18, 93 (2021).

The numbers are copied unchanged; only the layout changes (pomegranate JSON
-> plain arrays). Needs only the standard library:

    pip download gaitmap_mad==2.6.0 --no-deps && unzip gaitmap_mad-*.whl
    python3 export_gaitmap_hmm.py gaitmap_mad/stride_segmentation/hmm/_pre_trained_models/fallriskpd_at_lab_model.json \
        ../../web/models/roth-hmm.js
"""
import json
import sys

src, dst = sys.argv[1], sys.argv[2]
d = json.load(open(src))["params"]
ft = d["feature_transform"]["params"]
hmm = d["model"]["hmm"]
states = hmm["states"]
start, end = hmm["start_index"], hmm["end_index"]
emit = [i for i, s in enumerate(states) if s["distribution"] is not None]
assert emit == list(range(len(emit))), "emitting states must come first"
n = len(emit)

out_states = []
for i in emit:
    dist = states[i]["distribution"]
    assert dist["class"] == "GeneralMixtureModel"
    comps = []
    for w, c in zip(dist["weights"], dist["distributions"]):
        assert c["name"] == "MultivariateGaussianDistribution"
        mean, cov = c["parameters"]
        comps.append({"w": w, "mean": mean, "cov": cov})
    out_states.append({"name": states[i]["name"], "comps": comps})

trans = [[0.0] * n for _ in range(n)]
startp = [0.0] * n
to_end = 0
for a, b, p, *_ in hmm["edges"]:
    if a == start:
        startp[b] = p
    elif b == end:
        to_end += 1
    else:
        trans[a][b] = p
assert to_end == 0, "model with an end state is not supported"

n_trans = d["transition_model"]["params"]["n_states"]
n_stride = d["stride_model"]["params"]["n_states"]
model = {
    "source": "gaitmap_mad 2.6.0 fallriskpd_at_lab_model.json (AGPL-3.0-or-later)",
    "reference": "Roth N, Kuederle A, Ullrich M, et al. Hidden Markov Model based stride segmentation on unsupervised free-living gait data in Parkinson's disease patients. J NeuroEng Rehabil 18, 93 (2021). doi:10.1186/s12984-021-00883-7",
    "featureSpaceHz": ft["sampling_frequency_feature_space_hz"],
    "lowPass": {"order": ft["low_pass_filter"]["params"]["order"], "cutoffHz": ft["low_pass_filter"]["params"]["cutoff_freq_hz"]},
    "axes": ft["axes"],
    "features": ft["features"],
    "windowS": ft["window_size_s"],
    "standardize": ft["standardization"],
    "columns": d["data_columns"],
    "algorithm": d["algo_predict"],
    "transitionStates": n_trans,
    "strideStates": n_stride,
    "start": startp,
    "trans": trans,
    "states": out_states,
}
with open(dst, "w") as f:
    f.write(
        "// Generated by host/tools/export_gaitmap_hmm.py; do not edit by hand.\n"
        "// Pre-trained stride segmentation HMM from gaitmap_mad 2.6.0\n"
        "// (fallriskpd_at_lab_model.json) by the gaitmap authors,\n"
        "// Machine Learning and Data Analytics Lab, FAU Erlangen-Nuernberg.\n"
        "// Copyright (C) 2022 MaD-Lab Erlangen. Licensed AGPL-3.0-or-later:\n"
        "// see licenses/gaitmap-LICENSE.txt and licenses/AGPL-3.0.txt at the repo root.\n"
        "// SPDX-License-Identifier: AGPL-3.0-or-later\n"
        "// Model: Roth et al., J NeuroEng Rehabil 18, 93 (2021).\n"
        "export default "
    )
    json.dump(model, f, separators=(",", ":"))
    f.write(";\n")
print(f"{n} states ({n_trans} transition + {n_stride} stride) -> {dst}")
